#!/usr/bin/env python3
"""Rebuild the gold layer (sql/040_gold.sql) and regenerate docs/metrics.md.

Reads silver, writes only the gold schema, then renders gold.metric. Connects
with the repo .env file (PGHOST / PGPORT / PGDATABASE / PGUSER / PGPASSWORD;
CRLF line endings are tolerated).

Run (re-runnable, overwrites the document):
    .venv/bin/python scripts/report_metrics.py
"""
import argparse
import datetime
from pathlib import Path

import psycopg2

REPO = Path(__file__).resolve().parent.parent

# Display order and labels; every metric in gold.metric must appear here.
LABELS = {
    "closed_count": "Closed",
    "delivered_count": "Delivered",
    "ambiguous_count": "Ambiguous resolution",
    "closed_share": "Closed, % of issues",
    "delivered_share": "Delivered, % of issues",
    "delivered_of_closed": "Delivered, % of closed",
    "lead_time_median": "Lead time, median",
    "cycle_time_median": "Cycle time, median",
    "queue_time_median": "Queue time, median",
    "lead_time_median_never_started": "Lead time, median, never In Progress before done",
}


def load_env(path: Path) -> dict:
    env = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        env[k.strip()] = v.strip()
    return env


def fmt(value, unit: str) -> str:
    if value is None:
        return "-"
    if unit == "issues":
        return f"{int(value):,}"
    if unit == "percent":
        return f"{value:.1f}%"
    return f"{value:.2f} d"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--env", default=str(REPO / ".env"))
    ap.add_argument("--out", default=str(REPO / "docs" / "metrics.md"))
    args = ap.parse_args()

    env = load_env(Path(args.env))
    conn = psycopg2.connect(host=env.get("PGHOST", "127.0.0.1"), port=int(env.get("PGPORT", "5432")),
                            dbname=env["PGDATABASE"], user=env["PGUSER"], password=env["PGPASSWORD"])
    conn.autocommit = True
    cur = conn.cursor()
    cur.execute((REPO / "sql" / "040_gold.sql").read_text(encoding="utf-8"))
    cur.execute("SELECT max(fetched_at) FROM bronze.jira_issue_raw")
    snapshot = cur.fetchone()[0]
    cur.execute("""SELECT metric, scope, value, unit, n_included, n_excl_out_of_project,
                          n_excl_impossible_date, n_excl_not_applicable, note
                   FROM gold.metric""")
    rows = {(r[0], r[1]): r for r in cur.fetchall()}
    conn.close()

    unknown = {m for m, _ in rows} - set(LABELS)
    if unknown:
        raise SystemExit(f"gold.metric has metrics without a label: {sorted(unknown)}")

    lines = ["| Metric | All issues | Non-sub-tasks | Computed over (all / non-sub-tasks) "
             "| Excluded: out of project | Excluded: impossible date | Not applicable (all / non-sub-tasks) "
             "| Definition |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for metric, label in LABELS.items():
        a, n = rows[(metric, "all")], rows[(metric, "non_subtask")]
        lines.append(
            f"| {label} | {fmt(a[2], a[3])} | {fmt(n[2], n[3])} | {a[4]:,} / {n[4]:,} "
            f"| {a[5]:,} | {a[6]:,} | {a[7]:,} / {n[7]:,} | {a[8]} |")

    gen = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    doc = (
        "# Published metrics\n\n"
        f"Generated by `scripts/report_metrics.py` on {gen} from `gold.metric`\n"
        f"(`sql/040_gold.sql`). Data snapshot: bronze fetched up to {snapshot:%Y-%m-%d %H:%M UTC}.\n"
        "Definitions: `docs/metric_definitions.md`. \"Non-sub-tasks\" is *Delivered work*;\n"
        "\"All issues\" is *Closed pieces*.\n\n"
        + "\n".join(lines) + "\n"
    )
    out = Path(args.out)
    out.write_text(doc, encoding="utf-8")
    print(f"wrote {out} ({len(rows)} metric rows)")


if __name__ == "__main__":
    main()
